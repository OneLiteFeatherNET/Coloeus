// Generates the Material Design 3 color roles of the staff UI from one seed color. Run with `pnpm theme`; the output
// app/assets/css/md3-theme.css is committed, so a build never depends on this script running again. The functions are
// pure and imported by the unit tests; the file is written only when it is executed directly.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { Hct, MaterialDynamicColors, SchemeTonalSpot } from '@material/material-color-utilities'
import type { DynamicColor, DynamicScheme } from '@material/material-color-utilities'

export const SEED_COLOR = '#3D5A80'

/** The roles in output order: the CSS name without the `--md-sys-color-` prefix, and the key in MaterialDynamicColors. */
export const ROLES: ReadonlyArray<readonly [name: string, key: keyof typeof MaterialDynamicColors]> = [
  ['primary', 'primary'],
  ['on-primary', 'onPrimary'],
  ['primary-container', 'primaryContainer'],
  ['on-primary-container', 'onPrimaryContainer'],
  ['inverse-primary', 'inversePrimary'],
  ['secondary', 'secondary'],
  ['on-secondary', 'onSecondary'],
  ['secondary-container', 'secondaryContainer'],
  ['on-secondary-container', 'onSecondaryContainer'],
  ['tertiary', 'tertiary'],
  ['on-tertiary', 'onTertiary'],
  ['tertiary-container', 'tertiaryContainer'],
  ['on-tertiary-container', 'onTertiaryContainer'],
  ['error', 'error'],
  ['on-error', 'onError'],
  ['error-container', 'errorContainer'],
  ['on-error-container', 'onErrorContainer'],
  ['surface', 'surface'],
  ['surface-dim', 'surfaceDim'],
  ['surface-bright', 'surfaceBright'],
  ['surface-container-lowest', 'surfaceContainerLowest'],
  ['surface-container-low', 'surfaceContainerLow'],
  ['surface-container', 'surfaceContainer'],
  ['surface-container-high', 'surfaceContainerHigh'],
  ['surface-container-highest', 'surfaceContainerHighest'],
  ['on-surface', 'onSurface'],
  ['on-surface-variant', 'onSurfaceVariant'],
  ['outline', 'outline'],
  ['outline-variant', 'outlineVariant'],
  ['inverse-surface', 'inverseSurface'],
  ['inverse-on-surface', 'inverseOnSurface'],
  ['scrim', 'scrim'],
  ['shadow', 'shadow']
]

export type ThemeMode = 'light' | 'dark'

/** The role values of one mode as `#rrggbb`, keyed by the role name. */
export function rolesFor(seed: string, mode: ThemeMode): Record<string, string> {
  const hct = Hct.fromInt(argbFromHex(seed))
  const scheme: DynamicScheme = new SchemeTonalSpot(hct, mode === 'dark', 0)
  const roles: Record<string, string> = {}
  for (const [name, key] of ROLES) {
    const color = MaterialDynamicColors[key] as DynamicColor
    roles[name] = hexFromArgb(color.getArgb(scheme))
  }
  return roles
}

/** The stylesheet with the roles for light and dark, following the system preference and the data-theme attribute. */
export function generateThemeCss(seed: string = SEED_COLOR): string {
  const light = rolesFor(seed, 'light')
  const dark = rolesFor(seed, 'dark')
  const declarations = (values: Record<string, string>) => ROLES
    .map(([name]) => `  --md-sys-color-${name}: ${values[name]};`)
    .join('\n')
  return [
    `/* Generated by web/scripts/generate-theme.ts from the seed ${seed.toUpperCase()}. Do not edit by hand; run \`pnpm theme\`. */`,
    '/* Material Design 3 color roles, tonal spot scheme. The light roles apply unless the page asks for dark. */',
    ':root:not([data-theme="dark"]) {',
    declarations(light),
    '  color-scheme: light;',
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    declarations(dark).split('\n').map(line => `  ${line}`).join('\n'),
    '    color-scheme: dark;',
    '  }',
    '}',
    '',
    ':root[data-theme="dark"] {',
    declarations(dark),
    '  color-scheme: dark;',
    '}',
    ''
  ].join('\n')
}

/** WCAG contrast ratio of two `#rrggbb` colors, from 1 to 21. */
export function contrastRatio(first: string, second: string): number {
  const a = relativeLuminance(first)
  const b = relativeLuminance(second)
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05)
}

function relativeLuminance(hex: string): number {
  const linear = (offset: number) => {
    const value = parseInt(hex.slice(offset, offset + 2), 16) / 255
    return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4
  }
  return 0.2126 * linear(1) + 0.7152 * linear(3) + 0.0722 * linear(5)
}

function argbFromHex(hex: string): number {
  const value = parseInt(hex.replace('#', ''), 16)
  return 0xff000000 | value
}

function hexFromArgb(argb: number): string {
  return `#${((argb >> 16) & 0xff).toString(16).padStart(2, '0')}${((argb >> 8) & 0xff).toString(16).padStart(2, '0')}${(argb & 0xff).toString(16).padStart(2, '0')}`
}

const OUTPUT = new URL('../app/assets/css/md3-theme.css', import.meta.url)

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generateThemeCss(SEED_COLOR))
  process.stdout.write(`Wrote ${fileURLToPath(OUTPUT)}\n`)
}

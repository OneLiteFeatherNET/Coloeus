// Writes the Material Symbols the staff UI uses as path data into app/assets/icons/material-symbols.ts, so that the icons
// are self-hosted and no icon font or network request is needed. Run with `pnpm icons` after changing ICON_NAMES.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// The Iconify names of the outlined Material Symbols. The keys of the output are these names.
export const ICON_NAMES = [
  'add',
  'arrow-back',
  'arrow-forward',
  'account-circle',
  'check',
  'check-circle',
  'close',
  'currency-exchange',
  'dashboard',
  'error',
  'groups',
  'history',
  'info',
  'logout',
  'menu',
  'search'
] as const

interface IconSet {
  width?: number
  height?: number
  icons: Record<string, { body: string, width?: number, height?: number }>
}

const SOURCE = fileURLToPath(import.meta.resolve('@iconify-json/material-symbols/icons.json'))
const OUTPUT = new URL('../app/assets/icons/material-symbols.ts', import.meta.url)

export function renderIcons(set: IconSet): string {
  const entries = ICON_NAMES.map((name) => {
    const icon = set.icons[name]
    if (!icon) {
      throw new Error(`Material Symbol "${name}" is missing from the source set`)
    }
    const width = icon.width ?? set.width ?? 24
    const height = icon.height ?? set.height ?? 24
    const paths = [...icon.body.matchAll(/\bd="([^"]+)"/g)].map(match => match[1])
    return `  '${name}': { width: ${width}, height: ${height}, paths: [\n${paths.map(path => `    '${path}'`).join(',\n')}\n  ] }`
  })
  return [
    '// Generated by web/scripts/generate-icons.ts from @iconify-json/material-symbols. Do not edit by hand; run `pnpm icons`.',
    'export const materialSymbols = {',
    entries.join(',\n'),
    '} as const',
    '',
    'export type MaterialSymbolName = keyof typeof materialSymbols',
    ''
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const set = JSON.parse(readFileSync(SOURCE, 'utf8')) as IconSet
  writeFileSync(OUTPUT, renderIcons(set))
  process.stdout.write(`Wrote ${fileURLToPath(OUTPUT)}\n`)
}
